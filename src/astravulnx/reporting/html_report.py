"""Self-contained HTML report. All dynamic values are HTML-escaped."""

from __future__ import annotations

from html import escape

from astravulnx.__about__ import __version__
from astravulnx.models import Finding, ScanResult
from astravulnx.risk import summarize

_STYLE = """
body{font:15px/1.5 system-ui,-apple-system,"Segoe UI",sans-serif;color:#1b1f24;
 max-width:62rem;margin:2rem auto;padding:0 1rem}
h1{font-size:1.5rem;margin:0}
h2{font-size:1.1rem;margin-top:2rem;border-bottom:1px solid #d0d7de;padding-bottom:.3rem}
.meta{color:#57606a;margin:.25rem 0 1.5rem}
table{border-collapse:collapse;width:100%}
th,td{text-align:left;padding:.35rem .6rem;border-bottom:1px solid #eaeef2;vertical-align:top}
.summary td{width:1%;white-space:nowrap}
.finding{border:1px solid #d0d7de;border-left-width:5px;border-radius:4px;
 padding:.75rem 1rem;margin:1rem 0}
.finding h3{margin:0 0 .4rem;font-size:1rem}
.sev{font-weight:600;font-size:.8rem;letter-spacing:.03em}
code{font:13px ui-monospace,Menlo,Consolas,monospace;background:#f6f8fa;
 padding:.1rem .3rem;border-radius:3px;word-break:break-all}
dl{margin:.5rem 0 0;display:grid;grid-template-columns:8rem 1fr;gap:.2rem .75rem}
dt{color:#57606a}dd{margin:0}
.critical{border-left-color:#8b1a1a}.high{border-left-color:#cf222e}
.medium{border-left-color:#bf8700}.low{border-left-color:#0969da}
.info{border-left-color:#8c959f}
footer{margin-top:2.5rem;color:#57606a;font-size:.85rem}
"""


def _row(label: str, value: str) -> str:
    return f"<dt>{escape(label)}</dt><dd>{value}</dd>" if value else ""


def _finding_html(finding: Finding) -> str:
    location = escape(finding.url)
    if finding.parameter:
        location += (
            f" &mdash; parameter <code>{escape(finding.parameter)}</code> "
            f"({escape(finding.method)})"
        )
    payload = f"<code>{escape(finding.payload)}</code>" if finding.payload else ""
    return (
        f'<div class="finding {finding.severity.label.lower()}">'
        f'<h3><span class="sev">{escape(finding.severity.label.upper())}</span> '
        f"{escape(finding.title)}</h3>"
        f"<dl>{_row('Location', location)}{_row('Payload', payload)}"
        f"{_row('Evidence', escape(finding.evidence))}"
        f"{_row('Description', escape(finding.description))}"
        f"{_row('Remediation', escape(finding.remediation))}"
        f"{_row('References', escape(f'{finding.cwe} | {finding.owasp}'))}"
        f"{_row('Confidence', escape(finding.confidence.value))}</dl></div>"
    )


def render_html(result: ScanResult) -> str:
    summary = summarize(result.findings)
    counts = "".join(
        f"<tr><td>{escape(label)}</td><td>{count}</td></tr>"
        for label, count in summary.by_severity.items()
    )
    findings = "".join(_finding_html(f) for f in result.findings)
    findings = findings or "<p>No potential issues detected.</p>"
    errors = ""
    if result.errors:
        items = "".join(f"<li>{escape(e)}</li>" for e in result.errors)
        errors = f"<h2>Module errors</h2><ul>{items}</ul>"
    return (
        '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>AstraVulnX report - {escape(result.target)}</title>"
        f"<style>{_STYLE}</style></head><body>"
        f"<h1>AstraVulnX Assessment Report</h1>"
        f'<p class="meta">Target: <code>{escape(result.target)}</code><br>'
        f"Profile: {escape(result.profile)} &middot; "
        f"Started: {escape(result.started_at.isoformat())}"
        f" &middot; Duration: {result.duration_seconds:.1f}s &middot; Requests: {result.requests_sent}<br>"
        f"Modules: {escape(', '.join(result.modules))}</p>"
        f'<h2>Summary</h2><table class="summary">{counts}</table>'
        f"<h2>Findings ({summary.total})</h2>{findings}{errors}"
        f"<footer>Generated by AstraVulnX {escape(__version__)}. Findings are heuristic and must be "
        f"verified manually.</footer></body></html>\n"
    )


__all__ = ["render_html"]
